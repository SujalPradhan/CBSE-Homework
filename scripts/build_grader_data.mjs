// Copies the site's question and rubric files into the grader as ES modules, so the grader never drifts from the site.
// Run from the repo root: node scripts/build_grader_data.mjs
import fs from 'node:fs';
const out = 'worker/src';
fs.mkdirSync(out, { recursive: true });
const a = fs.readFileSync('docs/assignments.js', 'utf8');
const t = fs.readFileSync('docs/teacher-notes.js', 'utf8');
fs.writeFileSync(`${out}/assignments.mjs`, `// GENERATED by scripts/build_grader_data.mjs from docs/assignments.js. Do not edit.\n${a}\nexport { ASSIGNMENTS };\n`);
fs.writeFileSync(`${out}/teacher-notes.mjs`, `// GENERATED by scripts/build_grader_data.mjs from docs/teacher-notes.js. Do not edit.\n${t}\nexport { TEACHER };\n`);
console.log('wrote', `${out}/assignments.mjs`, `${out}/teacher-notes.mjs`);
